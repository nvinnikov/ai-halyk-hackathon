"""Диагностика шума в леджере: признак загрязнённости счёта и алярм на то,
что шум действительно вошёл в расчёт.

Здесь НЕТ отбора строк и нет вызовов модели. Отбрасывание неподлинных строк
измерено на приватном наборе и отвергнуто: шум не доходит до метрики ни через
категорию (читаются узкие статьи, а шум сидит в налогах, ФОТ и процентах), ни
через набор связанных сторон (там фильтр по контрагенту отсекает его сам),
поэтому апсайд у отбора нулевой, а цена одной ошибки — ячейка целиком, потому
что в читаемой категории строк от одной до пяти. Разбор — в
`docs/ops/ledger-noise.md`.

Признак загрязнённости — отношение максимальной суммы строки к медианной
внутри счёта. Он ДИАГНОСТИЧЕСКИЙ. Наборы им неразделимы: замер даёт публичный
диапазон примерно от шести до четырнадцати и приватный примерно от двенадцати
до двухсот пятидесяти — приватный минимум лежит НИЖЕ публичного максимума, и
никакой порог по этому признаку не отделяет чистую выгрузку от загрязнённой,
сколько его ни двигай. `POLLUTION_LEVEL` выбран как
«заметно выше типичного разброса внутри счёта», а не как граница между
наборами, и опираться на него как на границу нельзя.

Смысл алярма — сочетание. Загрязнённый счёт сам по себе не значит ничего:
шум лежит в категориях, которых ковенант не читает. Широкое чтение само по
себе тоже не значит ничего: на чистой выгрузке роллап законен. Опасно ровно
пересечение — договор потребовал «все операционные расходы», метрика честно
прочитала роллап, и вместе с настоящими статьями в него вошёл шум. Тогда
поднимается `polluted_rollup_read`, и ячейку надо смотреть глазами.
"""

import sys
from decimal import Decimal

sys.path.insert(0, "solution")
from dsl import Agg, CounterpartyIn, TxnIn, walk
from taxonomy import ROLLUPS

# Заметно выше типичного разброса сумм внутри одного счёта — и НЕ граница
# между наборами (см. докстринг модуля).
POLLUTION_LEVEL = Decimal("20")

# Фильтры, которые сужают роллап до заведомо названного множества: перечень
# связанных сторон и перечень операций. Шум в них не попадает — его
# контрагентов и его идентификаторов в этих перечнях нет. Период и квартал не
# сужают: подсаженные строки размазаны по всему году наравне с настоящими.
_NARROWING_FILTERS = (CounterpartyIn, TxnIn)


def _abs_amount(value) -> Decimal | None:
    """Модуль суммы строки или None, если суммы нет.

    Тотальна намеренно: признак диагностический, и любой неожиданный вид
    значения обязан просто выпасть из выборки, а не бросить исключение.
    Ближайший вызов сидит внутри сборки borrower-трейса, и брошенное отсюда
    исключение стоило бы всего трейса вместе с алярмом покрытия категорий.
    """
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, Decimal):
        return abs(value)
    if isinstance(value, int | float):
        return abs(Decimal(str(value)))
    return None


def pollution_ratio(rows: list[dict]) -> Decimal:
    """Отношение максимальной суммы строки к медианной; 0 при пустом входе.

    Медиана считается по модулям сумм на отсортированном списке — порядок
    строк на входе на результат не влияет. Строки без восстановленной суммы
    не участвуют. Ноль возвращается и при пустой выборке, и при нулевой
    медиане: и то и другое означает «признак не посчитан», а не «чисто».
    """
    amounts = sorted(a for a in (_abs_amount(r.get("amt")) for r in rows) if a is not None)
    if not amounts:
        return Decimal(0)
    mid = len(amounts) // 2
    median = amounts[mid] if len(amounts) % 2 else (amounts[mid - 1] + amounts[mid]) / 2
    if median == 0:
        return Decimal(0)
    return amounts[-1] / median


def is_polluted(rows: list[dict]) -> bool:
    return pollution_ratio(rows) >= POLLUTION_LEVEL


def wide_rollup_reads(node) -> list[str]:
    """Роллап-категории метрики, не суженные перечнем контрагентов или операций."""
    return sorted(
        {
            n.category
            for n in walk(node)
            if isinstance(n, Agg)
            and n.category in ROLLUPS
            and not any(isinstance(f, _NARROWING_FILTERS) for f in n.filters)
        }
    )


def rollup_alarm(account_id: str, ratio: Decimal, node) -> dict | None:
    """Алярм только на сочетании «счёт загрязнён» И «метрика читает роллап».

    По отдельности ни одно из двух ничего не значит, поэтому алярма на них по
    отдельности нет: он размылся бы и перестал читаться как повод посмотреть
    ячейку глазами.
    """
    if ratio < POLLUTION_LEVEL:
        return None
    categories = wide_rollup_reads(node)
    if not categories:
        return None
    return {
        "kind": "polluted_rollup_read",
        "account": account_id,
        "ratio": str(ratio),
        "categories": categories,
    }
